import { readFile } from "node:fs/promises";
const bundle = JSON.parse(await readFile(new URL("../data/dictionary-data.json", import.meta.url), "utf8"));
const audit = bundle.nsfwAudit;
if (!audit || !Array.isArray(audit.candidates) || !Array.isArray(bundle.tags)) throw new Error("Canonical NSFW audit metadata is missing.");
const known = new Set(bundle.tags.map(row => String(row?.[0] ?? "").normalize("NFKC").toLowerCase()));
const exact = audit.candidates.filter(item => known.has(String(item.tag ?? "").normalize("NFKC").toLowerCase())).length;
console.log("NSFW metadata candidate audit");
console.log("Canonical tags: " + bundle.tags.length);
console.log("Embedded candidates: " + audit.candidates.length);
console.log("Exact existing tags: " + exact);
console.log("Diagnostic only; no separate NSFW JSON is required.");
